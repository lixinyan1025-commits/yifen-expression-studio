export function drawCommonTopic(
  previousText?: string,
  random = () => crypto.getRandomValues(new Uint32Array(1))[0] / 2 ** 32,
): Topic {
  const pool = commonTopics.filter((topic) => topic.text !== previousText);
  const picked = pool[Math.min(pool.length - 1, Math.max(0, Math.floor(random() * pool.length)))];
  return { ...picked, id: crypto.randomUUID(), source: 'local', noteIds: [] };
}
